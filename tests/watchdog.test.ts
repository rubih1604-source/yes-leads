/**
 * ============================================================
 *  הסוכן הבודק - "מה שהוגדר, באמת קרה?"
 * ============================================================
 *
 *  **למה הוא נבנה.**
 *
 *  כל התקלות הכואבות כאן חלקו תכונה אחת: הן לא נכשלו.
 *  הן **פשוט לא קרו**. החוק הוגדר, המשימה נרשמה, המסך
 *  הראה מצב תקין - ואף הודעה לא יצאה. אין שגיאה ואין
 *  למה להסתכל.
 *
 *  בדיקה שמסתכלת על ההגדרות לא תתפוס את זה לעולם, כי
 *  ההגדרות תקינות. רק בדיקה שמסתכלת על **העובדות** תתפוס.
 *
 *  **והבדיקה הזו שומרת על השומר**, כי סוכן שנתקע, שרץ
 *  בתוך מה שהוא בודק, או שמתקן במסלול משלו - גרוע מאין
 *  סוכן בכלל: הוא נותן ביטחון שלא קיים.
 */

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

let passed = 0;
let failed = 0;

function test(name: string, fn: () => void) {
  try {
    fn();
    passed++;
    console.log(`  ✓ ${name}`);
  } catch (err) {
    failed++;
    console.error(`  ✗ ${name}`);
    console.error("     " + (err instanceof Error ? err.message : String(err)));
  }
}

const read = (p: string) => readFileSync(new URL(p, import.meta.url), "utf8");

const dog = read("../lib/watchdog.ts");
const boot = read("../instrumentation.ts");

/* ============================================================
 *  1. הוא בודק עובדות
 * ========================================================= */
console.log("\nהסוכן בודק מה קרה, לא מה הוגדר");

test("הבדיקה המרכזית: משימה שעבר זמנה ולא רצה", () => {
  /** זה המקרה המדויק: שינית סטטוס, חלפו 5 שעות, כלום */
  assert.ok(dog.includes("checkLateJobs"), "אין בדיקה למשימות תקועות");
  assert.ok(
    dog.includes('state: "pending", runAt: { lte: cutoff }'),
    "הבדיקה לא מחפשת משימות שזמנן עבר"
  );
});

test("גם השלב שלפני: סטטוס עם חוק, בלי משימה בכלל", () => {
  assert.ok(dog.includes("checkMissingJobs"), "אין בדיקה למשימות שלא נוצרו");
});

test("מנוע ששותק נתפס לפי הדופק האמיתי שלו", () => {
  /**
   * `engineRanAt` נרשם בסוף כל סבב, גם ריק. הסקה מ"מתי
   * רצה משימה" הייתה מבלבלת "אין מה לעשות" עם "מת".
   */
  assert.ok(dog.includes("engineRanAt"), "הדופק נמדד ממקור לא מדויק");
  assert.ok(
    dog.includes("if (waiting === 0) return null;"),
    "שקט בלי משימות ממתינות ידווח כתקלה"
  );
});

test("חוק שמצביע על תבנית שלא קיימת נתפס", () => {
  assert.ok(dog.includes("checkRuleTemplates"));
  assert.ok(
    dog.includes("!names.some((n) => usable.has(n))"),
    "חוק עם תבנית אחת שבורה מתוך שלוש ידווח כשבור"
  );
});

test("טבלת תבניות ריקה אינה ראיה לכלום", () => {
  /**
   * לפני הסנכרון הראשון הטבלה ריקה. בלי השורה הזו הסוכן
   * היה מכריז על **כל** החוקים כשבורים.
   */
  assert.ok(
    dog.includes("if (templates.length === 0) return null;"),
    "סנכרון שלא רץ ייראה כמו מערכת שבורה"
  );
});

/* ============================================================
 *  2. הוא מתקן דרך אותן פונקציות
 * ========================================================= */
console.log("\nהתיקון עובר בדלת הרגילה");

test("**אין מסלול שליחה משלו**", () => {
  /**
   * סוכן שמתקן במסלול משלו הוא מנגנון שני - בדיוק מה
   * שיצר את הבעיות מלכתחילה. הוא מריץ את אותו מנוע.
   */
  assert.ok(
    dog.includes('await import("./runner")'),
    "הסוכן לא משתמש במנוע הרגיל"
  );
  assert.ok(
    dog.includes('await import("./rules")'),
    "הסוכן לא משתמש בתזמון הרגיל"
  );
  assert.ok(
    !/sendTemplate|sendMessage|texterSend/.test(dog),
    "הסוכן שולח הודעות בעצמו - זה מנגנון שני"
  );
});

test("הוא לא כותב סטטוסים ולא נוגע בלידים", () => {
  assert.ok(
    !/db\.lead\.(update|updateMany|delete)/.test(dog),
    "הסוכן משנה לידים ישירות"
  );
});

test("תזמון מחדש מוגבל ליממה אחורה", () => {
  /**
   * בלי הגבול הזה הוא היה מתזמן הודעות ללקוחות מלפני
   * חודשים. זו בדיקה, לא מכונת זמן.
   */
  assert.ok(
    dog.includes("24 * 60 * 60_000"),
    "אין גבול זמן - לקוחות ישנים יוצפו בהודעות"
  );
});

test("הוא נוגע רק בערוץ שלך", () => {
  assert.ok(
    dog.includes("channel: MINE_CHANNEL"),
    "הסוכן יתזמן אוטומציות על לידים של הקונה"
  );
});

/* ============================================================
 *  3. מה שהוא לא פותר, הוא צועק
 * ========================================================= */
console.log("\nשקט אינו תשובה");

test("ממצא שלא טופל נכנס לפעמון", () => {
  assert.ok(dog.includes("raiseAlerts"), "אין התראות בכלל");
  assert.ok(
    dog.includes("if (!f.needsYou) continue;"),
    "גם מה שטופל מתריע - הפעמון יתמלא ברעש"
  );
});

test("ההתראה לא חוזרת כל 5 דקות", () => {
  assert.ok(
    dog.includes("20 * 60 * 60_000"),
    "אותה התראה תיכנס בכל סבב ותהפוך לרעש"
  );
});

/* ============================================================
 *  4. השומר לא יכול להירדם
 * ========================================================= */
console.log("\nהשומר עצמו");

test("**הוא רץ בטיימר נפרד מהמנוע**", () => {
  /**
   * תפקידו, בין השאר, לתפוס מנוע תקוע ולהעיר אותו. סוכן
   * שרץ בתוך המנוע היה נתקע יחד איתו - שומר שישן באותו
   * חדר עם מי שהוא שומר עליו.
   */
  assert.ok(
    boot.includes("setInterval(watch, WATCHDOG_MS)"),
    "לסוכן אין טיימר משלו"
  );

  const runner = read("../lib/runner.ts");
  assert.ok(
    !runner.includes("runWatchdog"),
    "הסוכן רץ בתוך המנוע - הוא ייתקע יחד איתו"
  );
});

test("בדיקה שנפלה לא מבטלת את השאר", () => {
  /**
   * אחרת סוכן שנועד לתפוס שקט היה הופך בעצמו לשקט.
   */
  assert.ok(
    dog.includes("for (const check of CHECKS)") &&
      dog.includes('code: "check_failed"'),
    "כשל בבדיקה אחת יפיל את כולן"
  );
});

test("הוא לא רץ על עצמו במקביל", () => {
  assert.ok(
    boot.includes("if (watching) return;"),
    "שתי בדיקות במקביל יתקנו את אותו דבר פעמיים"
  );
});

test("כל הבדיקות רשומות ברשימה אחת", () => {
  for (const check of [
    "checkEngineAlive",
    "checkLateJobs",
    "checkMissingJobs",
    "checkRuleTemplates",
    "checkDeliveries",
  ]) {
    const at = dog.indexOf("const CHECKS = [");
    assert.ok(
      dog.slice(at, at + 300).includes(check),
      `${check} נכתבה אבל לא רשומה - היא לא תרוץ לעולם`
    );
  }
});

// ------------------------------------------------------------
console.log(`\n${passed} בדיקות עברו, ${failed} נכשלו\n`);
if (failed > 0) process.exit(1);
