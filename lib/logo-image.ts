/**
 * ============================================================
 *  הלוגו של הדף
 * ============================================================
 *
 *  **הבעיה שזה פותר.** השדה ביקש כתובת אינטרנט ללוגו -
 *  ומי שיש לו את הלוגו כקובץ בטלפון לא יכול לעשות עם זה
 *  כלום. "תעלה את הקובץ לאיזה שירות ותביא קישור" זו
 *  משימה שלמה בפני עצמה, בשביל תמונה אחת קטנה.
 *
 *  לכן הלוגו נשמר כתמונה מוטמעת (`data:`) בתוך השדה
 *  הקיים. אין שירות אחסון, אין קישור שיכול למות, ואין
 *  תלות בשום דבר חיצוני - הלוגו נוסע עם הטופס.
 *
 *  ------------------------------------------------------------
 *  למה יש תקרת גודל
 *  ------------------------------------------------------------
 *
 *  התמונה המוטמעת יושבת בשורה בבסיס הנתונים ונשלחת מחדש
 *  בכל טעינה של הדף. צילום מסך של 4MB היה הופך דף נחיתה
 *  שנפתח בשנייה לדף שנטען עשר שניות ברשת סלולרית - ולקוח
 *  שמחכה הוא לקוח שסוגר. לכן הדפדפן מקטין את התמונה
 *  לפני השמירה, והשרת מסרב למה שעדיין גדול מדי.
 */

/** הרוחב והגובה שאליהם הדפדפן מקטין לפני השמירה */
export const LOGO_MAX_WIDTH = 480;
export const LOGO_MAX_HEIGHT = 160;

/**
 * תקרת הגודל של השדה השמור.
 *
 * ~400 אלף תווים הם בערך 300KB של תמונה. לוגו שטוח
 * בגודל הזה יוצא הרבה מתחת לזה; מה שחורג הוא צילום
 * מסך, ולא לוגו.
 */
export const LOGO_MAX_CHARS = 400_000;

/** סוגי התמונה שמתקבלים כלוגו מוטמע */
const DATA_IMAGE = /^data:image\/(png|jpeg|jpg|webp|gif|svg\+xml);base64,[a-z0-9+/=\s]+$/i;

/** כתובת רגילה באינטרנט */
const HTTP_URL = /^https?:\/\/\S+$/i;

export type LogoCheck = { ok: boolean; reason?: string };

/**
 * האם אפשר לשמור את הערך הזה כלוגו.
 *
 * **שתי צורות בלבד**, ושתיהן בטוחות להצגה בדף ציבורי:
 * כתובת http(s), או תמונה מוטמעת. כל דבר אחר - ובעיקר
 * `javascript:` - הוא דלת שלא צריכה להיות פתוחה בדף
 * שפתוח לאינטרנט כולו.
 */
export function checkLogo(value: string): LogoCheck {
  const v = value.trim();

  if (!v) return { ok: true };

  if (v.length > LOGO_MAX_CHARS) {
    return {
      ok: false,
      reason: "התמונה גדולה מדי. נסה לוגו קטן יותר או חתוך אותו.",
    };
  }

  if (HTTP_URL.test(v)) return { ok: true };
  if (DATA_IMAGE.test(v)) return { ok: true };

  return {
    ok: false,
    reason: "צריך קובץ תמונה או כתובת שמתחילה ב-https",
  };
}

/** האם הערך הוא תמונה מוטמעת (ולא כתובת) */
export function isEmbeddedLogo(value: string): boolean {
  return DATA_IMAGE.test(value.trim());
}
