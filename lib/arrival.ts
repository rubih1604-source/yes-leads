/**
 * ============================================================
 *  הגעה חוזרת צפה לראש הרשימה
 * ============================================================
 *
 *  **הכלל, במילים שלך.**
 *
 *  כל ליד שנכנס - לא משנה מאיזו דלת ולא משנה מה התווית
 *  שלו - מופיע בראש הרשימה עם התאריך של עכשיו. אם המספר
 *  כבר קיים, הוא מסומן "ליד כפול", והכניסות הקודמות
 *  נשמרות ומוצגות בתוך הכרטיס.
 *
 *  **למה הקובץ הזה קיים.**
 *
 *  הכלל היה כתוב בתוך הוובוק של ליד מנגר בלבד. ליד
 *  שנכנס ידנית קיבל כניסה חדשה ותווית "כפול" - אבל
 *  התאריך שלו נשאר הישן, ולכן הוא נשאר קבור באמצע
 *  הרשימה ולא נראה. אותו כלל, שתי התנהגויות, תלוי
 *  בדלת.
 *
 *  מעכשיו הכלל נמצא **כאן בלבד**, וכל דלת קוראת לו.
 *  דלת חדשה שתיווסף ולא תקרא לו תיתפס בבדיקה.
 *
 *  טהור בכוונה: ההחלטה נפרדת מהכתיבה למסד, כדי שאפשר
 *  יהיה לבדוק אותה.
 */

export type ArrivalFacts = {
  /**
   * אותה הגשה בדיוק שהגיעה משתי דלתות.
   *
   * זו לא הגעה חדשה - זה אותו אדם שמילא טופס אחד,
   * והמערכת שמעה עליו פעמיים. הקפצה כאן הייתה מזיזה
   * את הליד בלי שקרה כלום.
   */
  sameSubmission?: boolean;
  /**
   * הכניסה הזו שייכת לקונה ולא לך.
   *
   * ליד שנמכר יצא מהרשימה שלך, וכניסה אצל הקונה לא
   * אמורה להזיז שום דבר אצלך.
   */
  isSale?: boolean;
};

/**
 * האם ההגעה הזו מקפיצה את הליד לראש הרשימה שלך.
 *
 * ברירת המחדל היא **כן**. כל חריג חייב להיות מוצהר
 * במפורש - ככה דלת חדשה שלא חשבה על זה מתנהגת נכון
 * מעצמה.
 */
export function bumpsToTop(facts: ArrivalFacts): boolean {
  if (facts.sameSubmission === true) return false;
  if (facts.isSale === true) return false;
  return true;
}

/**
 * הערך שנכתב לשדה intakeAt בעדכון של ליד קיים.
 *
 * undefined פירושו "אל תיגע בתאריך" - וזו בדיוק הצורה
 * ש-Prisma מצפה לה כדי להשאיר שדה כמו שהוא.
 */
export function arrivalIntakeAt(
  facts: ArrivalFacts,
  now: Date = new Date()
): Date | undefined {
  return bumpsToTop(facts) ? now : undefined;
}

/**
 * התווית שמוצגת על ליד שנכנס יותר מפעם אחת.
 *
 * נגזרת ממספר הכניסות ולא נשמרת בנפרד, כדי שלא תוכל
 * לסתור את מה שבאמת רשום בכרטיס.
 */
export function duplicateLabel(entryCount: number): string | null {
  if (entryCount <= 1) return null;
  return `כפול · ${entryCount}`;
}

/**
 * ============================================================
 *  הקפצה בפועל - דלת אחת לכתיבה
 * ============================================================
 *
 *  **למה גם הכתיבה כאן, ולא רק ההחלטה.**
 *
 *  כל עוד כל דלת כתבה את העדכון בעצמה, מספיק היה שדלת
 *  אחת תשכח - וזה בדיוק מה שקרה בדלת הידנית. עכשיו יש
 *  פונקציה אחת שכל דלת קוראת לה, וכשלון שלה לעולם לא
 *  מפיל את קליטת הליד: עדיף ליד שנקלט במקום הלא נכון
 *  מאשר ליד שלא נקלט.
 */
export async function bumpArrival(
  client: {
    lead: {
      update: (args: {
        where: { id: string };
        data: { intakeAt: Date };
      }) => Promise<unknown>;
    };
  },
  leadId: string,
  facts: ArrivalFacts,
  now: Date = new Date()
): Promise<boolean> {
  if (!bumpsToTop(facts)) return false;

  try {
    await client.lead.update({
      where: { id: leadId },
      data: { intakeAt: now },
    });
    return true;
  } catch {
    return false;
  }
}
