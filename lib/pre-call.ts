/** כמה דקות לפני התזכורת מותר לשלוח */
export const MIN_LEAD_MINUTES = 15;
export const MAX_LEAD_MINUTES = 30;

/**
 * כמה דקות לפני התזכורת הזו תצא ההתראה.
 *
 * **נגזר מהמזהה של התזכורת ולא מהגרלה חדשה בכל סיבוב.**
 * הגרלה חדשה הייתה משנה את התשובה בכל פעם שהמנוע מתעורר,
 * ואז ההתראה הייתה יוצאת או מוקדם מדי או בכלל לא - תלוי
 * במזל של אותה דקה.
 */
export function leadMinutesFor(taskId: string): number {
  let hash = 2166136261;

  for (let i = 0; i < taskId.length; i++) {
    hash ^= taskId.charCodeAt(i);
    hash = Math.imul(hash, 16777619) >>> 0;
  }

  /**
   * ערבול אחרון.
   *
   * בלי זה מזהים שנראים דומה - וכל המזהים במערכת נראים
   * דומה, כי הם נוצרים ברצף - היו נופלים כמעט כולם על
   * אותו מספר דקות. ההתראות היו יוצאות כולן באותו הפרש,
   * וזה בדיוק מה שביקשת שלא יקרה.
   */
  hash ^= hash >>> 15;
  hash = Math.imul(hash, 2246822507) >>> 0;

  /**
   * `>>> 0` ולא רק `^` - ב-JavaScript פעולת XOR מחזירה
   * מספר **מסומן**, ואז השארית יוצאת שלילית וההתראה
   * נוחתת מחוץ לטווח שביקשת. זה נתפס בסימולציה, לא
   * בקריאה.
   */
  hash = (hash ^ (hash >>> 13)) >>> 0;

  const span = MAX_LEAD_MINUTES - MIN_LEAD_MINUTES + 1;
  return MIN_LEAD_MINUTES + (hash % span);
}

/**
 * האם הגיע הרגע לשלוח את ההתראה המקדימה.
 *
 * **שני גבולות, ושניהם חשובים:**
 *
 *  - לא לפני החלון, אחרת זו לא התראה "לפני השיחה".
 *  - **לא אחרי שהתזכורת עצמה כבר הגיעה.** אחרת היית מקבל
 *    "תתקשר עכשיו, לפני השני" בדיוק כשהתזכורת האמיתית
 *    כבר צלצלה - שתי התראות על אותו דבר, אחת מהן מיותרת.
 *
 * תזכורת שנקבעה לעוד עשר דקות בלבד עדיין מקבלת התראה
 * מיד: החלון כבר נפתח, והדחיפה רלוונטית בדיוק כמו תמיד.
 */
export function shouldNudge(params: {
  taskId: string;
  dueAt: Date;
  now: Date;
}): boolean {
  const lead = leadMinutesFor(params.taskId) * 60_000;
  const due = params.dueAt.getTime();
  const now = params.now.getTime();

  return now >= due - lead && now < due;
}

/**
 * המלל הבא בתור.
 *
 * סבב ולא הגרלה: הגרלה הייתה חוזרת על אותה שורה פעמיים
 * ברצף, וזה בדיוק מה שהופך את ההתראה לרעש.
 */
export function nudgeAt(cursor: number): string {
  const index = ((cursor % NUDGES.length) + NUDGES.length) % NUDGES.length;
  return NUDGES[index];
}
