/**
 * ============================================================
 *  זיהוי בקשת הסרה
 * ============================================================
 *
 *  **למה זיהוי ודאי ולא רק הבוט החכם.**
 *
 *  עד היום רק הסיווג של קלוד קבע מי ביקש להסיר. זה אומר
 *  ששליחה למי שביקש להסיר תלויה בשירות חיצוני: אם הוא
 *  איטי, נפל, או שהמפתח פג - הבקשה פשוט לא נרשמת, והאדם
 *  מקבל דיוור נוסף.
 *
 *  לכן יש כאן שכבה ודאית שרצה **לפני** הסיווג: ניסוחים
 *  שאין עליהם ויכוח מסומנים מיד, בלי רשת ובלי תלות באף
 *  שירות. הסיווג החכם ממשיך לרוץ אחריה ותופס את מה שמנוסח
 *  אחרת - שניהם מזינים את **אותה** רשימה שחורה.
 *
 *  הקובץ טהור בכוונה - בלי מסד ובלי רשת - כדי שהזיהוי
 *  יהיה מכוסה בבדיקות. טעות כאן היא או אדם שממשיך לקבל
 *  הודעות אחרי שביקש להפסיק, או ליד שנמחק בטעות.
 */

/** התבניות עצמן, לבדיקה שאין בהן אותיות סופיות */
export function patternSources(): string[] {
  return [...REMOVAL, ...NOT_INTERESTED, CONTRAST].map((r) => r.source);
}

export type UnsubscribeMatch = {
  /** האם לסמן ברשימה השחורה */
  blacklist: boolean;
  /** מה בדיוק זוהה - נרשם על הליד כדי שתדע למה הוא שם */
  reason: string | null;
};

/**
 * מיישר את הטקסט להשוואה.
 *
 * מוריד ניקוד, סימני פיסוק ורווחים כפולים, ומאחד יו"ד
 * כפולה - "אליי" ו"אלי" הם אותו דבר בכתיב חופשי.
 *
 * **אותיות סופיות מומרות לרגילות.** כאן נפלה הבדיקה
 * הראשונה: "לא מעוניין" נגמר ב-ן סופית, והתבנית חיפשה נ
 * רגילה - ולכן הניסוח הנפוץ ביותר לא זוהה. ההמרה כאן
 * פותרת את זה פעם אחת לכל התבניות, במקום לתקן כל אחת
 * מהן בנפרד ולשכוח את הבאה.
 */
const FINAL_LETTERS: Record<string, string> = {
  "ם": "מ",
  "ן": "נ",
  "ך": "כ",
  "ף": "פ",
  "ץ": "צ",
};

export function normalizeText(input: string): string {
  return (input ?? "")
    .trim()
    .toLowerCase()
    .replace(/[֑-ׇ]/g, "")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/[םןךףץ]/g, (ch) => FINAL_LETTERS[ch] ?? ch)
    .replace(/יי/g, "י")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * ניסוחים שאין עליהם ויכוח.
 *
 * כל אחד מהם פירושו "אל תשלחו לי יותר", בלי קשר להקשר
 * ובלי קשר למה עוד כתוב בהודעה.
 */
const REMOVAL = [
  /(^|\s)(הסר|הסירו|תסירו|תסיר)(\s|$)/,
  /(להסיר|תסיר|תסירו|הסירו)\s+אותי/,
  /(תפסיק|תפסיקו|תפסיקי|הפסיקו)\s+(לשלוח|להציק|לשגר)/,
  /אל\s+תשלח(ו|י)?/,
  /לא\s+לשלוח/,
  /(תמחק|תמחקו|למחוק|שימחקו|מחקו|תמחקי)\s+(את\s+)?(המספר|הטלפונ|אותי)/,
  /(הורידו|תוריד|תורידו)\s+אותי/,
  /אל\s+(תפנו|תפנה|תתקשר|תתקשרו)\s+אלי/,
  /לא\s+(לפנות|להתקשר)\s+אלי/,
  /(^|\s)(stop|unsubscribe|remove)(\s|$)/,
];

/** חוסר עניין מפורש */
const NOT_INTERESTED = [
  /לא\s+מעונינ/,
  /לא\s+רלוונטי/,
];

/**
 * מילות ניגוד.
 *
 * "לא מעוניין בזה **אבל** תשלח לי על האינטרנט" הוא לקוח
 * מתעניין, לא בקשת הסרה. בניסוח כזה השכבה הוודאית מרימה
 * ידיים ומשאירה את ההכרעה לסיווג החכם - שמבין משמעות.
 *
 * זה לא חל על בקשת הסרה מפורשת: "תסירו אותי אבל תודה"
 * הוא עדיין בקשת הסרה.
 */
const CONTRAST_WORDS = ["אבל", "אלא", "חוץ", "למעט", "רק"];

/**
 * נבנית מהמילים אחרי נרמול, ולא נכתבת ביד כתבנית.
 *
 * "חוץ" נגמר ב-ץ סופית, והנרמול הופך אותה ל-צ. תבנית
 * שנכתבה ביד עם האות הסופית פשוט לא מתאימה לעולם - וזה
 * כשל שקט שאי אפשר לראות בקריאת הקוד.
 */
const CONTRAST = new RegExp(
  `(^|\\s)(${CONTRAST_WORDS.map((w) => normalizeText(w)).join("|")})(\\s|$)`
);

/**
 * האם ההודעה הזו היא בקשה להפסיק לקבל הודעות.
 *
 * מחזיר גם את הסיבה, כדי שבמסך הרשימה השחורה תראה **למה**
 * כל אדם נמצא שם ולא תצטרך לנחש.
 */
export function detectUnsubscribe(text: string): UnsubscribeMatch {
  const clean = normalizeText(text);

  if (!clean) return { blacklist: false, reason: null };

  for (const pattern of REMOVAL) {
    if (pattern.test(clean)) {
      return { blacklist: true, reason: "ביקש להסיר" };
    }
  }

  if (CONTRAST.test(clean)) return { blacklist: false, reason: null };

  for (const pattern of NOT_INTERESTED) {
    if (pattern.test(clean)) {
      return { blacklist: true, reason: "אמר שלא מעוניין" };
    }
  }

  return { blacklist: false, reason: null };
}

/**
 * האם כוונה שהסיווג החכם החזיר מחייבת רשימה שחורה.
 *
 * אותה רשימה בדיוק - הסיווג הוא דלת שנייה אליה, לא רשימה
 * משלו.
 */
export function intentBlacklists(
  intent: string,
  confidence: number
): UnsubscribeMatch {
  if (confidence < 0.85) return { blacklist: false, reason: null };

  if (intent === "remove") {
    return { blacklist: true, reason: "ביקש להסיר" };
  }

  if (intent === "not_interested") {
    return { blacklist: true, reason: "אמר שלא מעוניין" };
  }

  return { blacklist: false, reason: null };
}
